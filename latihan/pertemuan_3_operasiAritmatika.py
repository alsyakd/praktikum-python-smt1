# operasi aritmatika 
 
a = 10 
b = 3 
 
# operasi tambah + 
hasil = a + b 
print(a, '+', b, '=', hasil) 
 
# operasi kurang – 
hasil = a - b 
print(a, '-', b, '=', hasil) 
 
# operasi perkalian * 
hasil = a * b 
print(a, '*', b, '=', hasil) 
 
# operasi pembagian / 
hasil = a / b 
print(a, '/', b, '=', hasil) 
 
# operasi eksponen (pangkat) ** 
hasil = a ** b 
print(a, '**', b, '=', hasil) 
 
# operasi modulus (sisa dari hasil bagi) % 
hasil = a % b 
print(a, '%', b, '=', hasil) 
 
# operasi floor division (pembagian bulat) // 
hasil = a // b 
print(a, '//', b, '=', hasil)
